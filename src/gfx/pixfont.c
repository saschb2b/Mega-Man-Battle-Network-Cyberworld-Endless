#define CELL_W 8
#define CHARS 128
#define SPACE_W 2

static SDL_Texture *atlas;
static int atlas_lost;          /* (P.textures_lost when it was made) */
static uint8_t widths[CHARS];

static void build(void) {
	static uint32_t px[CELL_W * CHARS * PIXFONT_H];
	memset(px, 0, sizeof px);
	memset(widths, 0, sizeof widths);
	for (size_t g = 0; g < sizeof glyphs / sizeof *glyphs; ++g) {
		unsigned ch = (unsigned char)glyphs[g].ch;
		int w = 0;
		for (int r = 0; r < PIXFONT_H && glyphs[g].rows[r]; ++r) {
			const char *row = glyphs[g].rows[r];
			int n = (int)strlen(row);
			if (n > w) w = n;
			for (int c = 0; c < n && c < CELL_W; ++c)
				if (row[c] == '#') px[r * CELL_W * CHARS + ch * CELL_W + c] = 0xFFFFFFFFu;
		}
		widths[ch] = (uint8_t)(w < CELL_W ? w : CELL_W);
	}
	widths[' '] = SPACE_W;
	SDL_Surface *s = SDL_CreateRGBSurfaceWithFormatFrom(px, CELL_W * CHARS, PIXFONT_H, 32, CELL_W * CHARS * 4, SDL_PIXELFORMAT_ARGB8888);
	if (!s) return;
	atlas = SDL_CreateTextureFromSurface(P.renderer, s);
	SDL_FreeSurface(s);
	if (atlas) SDL_SetTextureBlendMode(atlas, SDL_BLENDMODE_BLEND);
	atlas_lost = P.textures_lost;
}

/* the letter `ch` stands for: a character the font lacks is a space */
static unsigned glyph_of(unsigned char ch) {
	if (!widths['A']) {
		/* (the widths without the texture: a layout before the first draw) */
		for (size_t g = 0; g < sizeof glyphs / sizeof *glyphs; ++g) {
			int w = 0;
			for (int r = 0; r < PIXFONT_H && glyphs[g].rows[r]; ++r) {
				int n = (int)strlen(glyphs[g].rows[r]);
				if (n > w) w = n;
			}
			widths[(unsigned char)glyphs[g].ch] = (uint8_t)w;
		}
		widths[' '] = SPACE_W;
	}
	return ch < CHARS && widths[ch] ? ch : ' ';
}

int pixfont_width(const char *s, int scale) {
	int w = 0, n = 0;
	for (const unsigned char *p = (const unsigned char *)s; *p; ++p, ++n) w += widths[glyph_of(*p)] + 1;
	return n ? (w - 1) * scale : 0;
}

void pixfont_draw(int x, int y, const char *s, SDL_Color c, SDL_Color shade, int align, int scale) {
	if (atlas && atlas_lost != P.textures_lost) {
		SDL_DestroyTexture(atlas);
		atlas = NULL;
	}
	if (!atlas) build();
	if (!atlas || !s || !*s) return;
	if (align == PIXFONT_CENTER) x -= pixfont_width(s, scale) / 2;
	else if (align == PIXFONT_RIGHT) x -= pixfont_width(s, scale);
	for (int pass = shade.a ? 0 : 1; pass < 2; ++pass) {
		SDL_Color k = pass ? c : shade;
		int o = pass ? 0 : scale, cx = x;
		SDL_SetTextureColorMod(atlas, k.r, k.g, k.b);
		SDL_SetTextureAlphaMod(atlas, k.a);
		for (const unsigned char *p = (const unsigned char *)s; *p; ++p) {
			unsigned ch = glyph_of(*p);
			int w = widths[ch];
			if (ch != ' ') {
				SDL_Rect src = { (int)ch * CELL_W, 0, w, PIXFONT_H }, dst = { cx + o, y + o, w * scale, PIXFONT_H * scale };
				SDL_RenderCopy(P.renderer, atlas, &src, &dst);
			}
			cx += (w + 1) * scale;
		}
	}
}

int pixfont_wrap(const char *text, int w, int scale, char lines[][96], int most) {
	int n = 0;
	const char *p = text;
	while (*p && n < most) {
		while (*p == ' ') ++p;
		char line[96] = "";
		int len = 0;
		/* (words while they fit, a word too long for a line cut where it must) */
		while (*p && *p != '\n') {
			size_t word = strcspn(p, " \n");
			char next[96];
			snprintf(next, sizeof next, "%s%s%.*s", line, len ? " " : "", (int)(word < 90 ? word : 90), p);
			if (len && pixfont_width(next, scale) > w) break;
			if (!len && pixfont_width(next, scale) > w) {
				size_t cut = word;
				while (cut > 1) {
					snprintf(next, sizeof next, "%.*s", (int)--cut, p);
					if (pixfont_width(next, scale) <= w) break;
				}
				snprintf(line, sizeof line, "%s", next);
				p += cut;
				len = (int)cut;
				break;
			}
			snprintf(line, sizeof line, "%s", next);
			len = (int)strlen(line);
			p += word;
			while (*p == ' ') ++p;
		}
		if (*p == '\n') ++p;
		snprintf(lines[n++], 96, "%s", line);
	}
	return n;
}
